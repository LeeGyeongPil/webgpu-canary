// Records healthy reference outputs from REAL runs on Node cpu and writes
//   fixtures/minilm.json, fixtures/smollm2.json and src/testing/fixtures-data.ts
// Needs network the first time (model download; behind a proxy set NODE_USE_ENV_PROXY=1) and `npm run build`.
// It is resumable: finished (model, dtype) pairs are kept in .cache/record-partial.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformersLoader, transformersVersion } from '../dist/transformers/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = path.join(root, '.cache');
const partialFile = path.join(cacheDir, 'record-partial.json');
const loader = transformersLoader({ cacheDir });
const libVersion = await transformersVersion({ cacheDir });
const partial = fs.existsSync(partialFile) ? JSON.parse(fs.readFileSync(partialFile, 'utf8')) : {};

const MODELS = [
  {
    file: 'minilm', key: 'vectors', task: 'embeddings', modelId: 'Xenova/all-MiniLM-L6-v2',
    revision: '751bff37182d3f1213fa05d7196b954e230abad9',
    input: 'The quick brown fox jumps over the lazy dog.', dtypes: ['fp32', 'q8', 'fp16', 'q4', 'q4f16'],
  },
  {
    file: 'smollm2', key: 'tokens', task: 'text-generation', modelId: 'HuggingFaceTB/SmolLM2-135M-Instruct',
    revision: '12fd25f77366fa6b3b4b768ec3050bf629380bac',
    input: 'What is the capital of France? Answer in one word.', maxNewTokens: 12, dtypes: ['fp32', 'fp16', 'q4', 'q4f16'],
  },
];

const round = (v) => v.map((x) => Math.round(x * 1e8) / 1e8);
const signal = new AbortController().signal;

for (const m of MODELS) {
  partial[m.file] ??= {};
  for (const dtype of m.dtypes) {
    if (partial[m.file][dtype]) continue;
    console.log(`recording ${m.modelId} cpu/${dtype} ...`);
    const runner = await loader.load(m.modelId, m.revision, { device: 'cpu', dtype }, m.task, signal);
    const out = await runner.run(m.input, { maxNewTokens: m.maxNewTokens });
    await runner.dispose();
    partial[m.file][dtype] = m.task === 'embeddings' ? round(Array.from(out.vector)) : out.tokens;
    fs.writeFileSync(partialFile, JSON.stringify(partial));
  }
}

const data = {};
fs.mkdirSync(path.join(root, 'fixtures'), { recursive: true });
for (const m of MODELS) {
  const doc = {
    note: 'Recorded on Node cpu with transformers.js; healthy reference values for the mock mode.',
    modelId: m.modelId, revision: m.revision, task: m.task, input: m.input,
    ...(m.maxNewTokens ? { maxNewTokens: m.maxNewTokens } : {}),
    libVersion, recordedAt: new Date().toISOString().slice(0, 10), device: 'cpu',
    [m.key]: partial[m.file],
  };
  data[m.file] = doc;
  fs.writeFileSync(path.join(root, 'fixtures', `${m.file}.json`), JSON.stringify(doc, null, 1) + '\n');
}
const ts =
  '// Generated by scripts/record-fixtures.mjs from real Node cpu runs. Do not edit by hand.\n' +
  `export const fixtures = ${JSON.stringify(data)} as const;\n`;
fs.writeFileSync(path.join(root, 'src', 'testing', 'fixtures-data.ts'), ts);
console.log('wrote fixtures/*.json and src/testing/fixtures-data.ts');
